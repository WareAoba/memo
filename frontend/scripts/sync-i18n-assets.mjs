import { readFileSync, writeFileSync } from 'node:fs';
import { format } from 'prettier';
const read = (path) => JSON.parse(readFileSync(new URL(path, import.meta.url), 'utf8'));
const manifest = read('../public/manifest.webmanifest');
const messages = {};
for (const language of ['ko', 'en', 'ja']) {
  const catalog = read(`../src/i18n/locales/${language}.json`);
  messages[language] = catalog['Reminders.valueStartsAtValueValue'];
  writeFileSync(
    new URL(`../public/manifest.${language}.webmanifest`, import.meta.url),
    JSON.stringify({ ...manifest, name: catalog['app.title'], lang: language }, null, 2) + '\n',
  );
}
writeFileSync(
  new URL('../public/notification-locales.js', import.meta.url),
  await format(
    '/* Generated by scripts/sync-i18n-assets.mjs from the i18next catalogs. */\nself.reminderMessages = ' +
      JSON.stringify(messages, null, 2) +
      ';\n',
    { parser: 'babel', singleQuote: true, printWidth: 100 },
  ),
);
